"""Embed the pages in web/ into the firmware as gzip bytes (src/web_pages.h): dashboard.html ->
DASHBOARD_GZ / DASHBOARD_GZ_LEN, draw.html -> DRAW_GZ / DRAW_GZ_LEN, ...

Runs before every `pio run` (extra_scripts in platformio.ini), or by hand:
    python embed_web.py
The output is deterministic (gzip mtime 0, OS byte fixed), so an unchanged page gives an unchanged
header on any machine.
"""
import gzip
from pathlib import Path

try:
    Import("env")                      # noqa: F821  (PlatformIO pre-build script)
    HERE = Path(env["PROJECT_DIR"])    # noqa: F821
except NameError:
    HERE = Path(__file__).resolve().parent

WEB = HERE / "web"
OUT = HERE / "src" / "web_pages.h"


def build():
    parts = ["// Generated by embed_web.py from web/*.html - edit those, not this.\n"
             "#pragma once\n#include <pgmspace.h>\n"]
    for src in sorted(WEB.glob("*.html")):
        html = src.read_bytes().replace(b"\r\n", b"\n")   # same bytes whatever git did to line endings
        gz = gzip.compress(html, compresslevel=9, mtime=0)
        gz = gz[:9] + b"\xff" + gz[10:]                  # OS byte: Python writes 0xff on Windows, 3 on Linux
        name = src.stem.upper() + "_GZ"
        rows = [", ".join(f"0x{b:02x}" for b in gz[i:i + 20]) for i in range(0, len(gz), 20)]
        parts.append(f"\n// {src.name}: {len(html)} B -> {len(gz)} B\n"
                     f"static const size_t {name}_LEN = {len(gz)};\n"
                     f"static const uint8_t {name}[] PROGMEM = {{\n  " + ",\n  ".join(rows) + "\n};\n")
    text = "".join(parts)
    if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
        OUT.write_text(text, encoding="utf-8", newline="\n")
        print(f"embed_web: {', '.join(p.name for p in sorted(WEB.glob('*.html')))} -> {OUT.name}")


build()
