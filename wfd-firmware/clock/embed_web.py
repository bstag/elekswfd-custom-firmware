"""Embed web/dashboard.html into the firmware as gzip bytes (src/web_dashboard.h).

Runs before every `pio run` (extra_scripts in platformio.ini), or by hand:
    python embed_web.py
The output is deterministic (gzip mtime 0), so an unchanged page gives an unchanged header.
"""
import gzip
from pathlib import Path

try:
    Import("env")                      # noqa: F821  (PlatformIO pre-build script)
    HERE = Path(env["PROJECT_DIR"])    # noqa: F821
except NameError:
    HERE = Path(__file__).resolve().parent

SRC = HERE / "web" / "dashboard.html"
OUT = HERE / "src" / "web_dashboard.h"


def build():
    html = SRC.read_bytes().replace(b"\r\n", b"\n")   # same bytes whatever git did to line endings
    gz = gzip.compress(html, compresslevel=9, mtime=0)
    rows = [", ".join(f"0x{b:02x}" for b in gz[i:i + 20]) for i in range(0, len(gz), 20)]
    text = ("// Generated by embed_web.py from web/dashboard.html - edit that, not this.\n"
            "#pragma once\n#include <pgmspace.h>\n"
            f"static const size_t DASHBOARD_GZ_LEN = {len(gz)};\n"
            "static const uint8_t DASHBOARD_GZ[] PROGMEM = {\n  " + ",\n  ".join(rows) + "\n};\n")
    if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
        OUT.write_text(text, encoding="utf-8", newline="\n")
        print(f"embed_web: {SRC.name} {SRC.stat().st_size} B -> {len(gz)} B gzip")


build()
